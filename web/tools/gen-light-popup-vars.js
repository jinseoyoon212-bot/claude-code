/**
 * Generates web/styles/light-popup-vars.scss: the app's own Classic Light colour variables, scoped to
 * the popups (see web/styles/popups.scss). Run it after upstream changes ts/themes:
 *
 *   node -r tsx/cjs web/tools/gen-light-popup-vars.js
 *
 * The theme code is only read at build time (not bundled into the page) because importing
 * ts/themes/constants/colors.tsx at page start would run app modules before the logger is ready.
 */
const Module = require('module');
const path = require('path');
const fs = require('fs');

// colors.tsx calls tr() at import time for theme titles; the values are irrelevant here
const originalLoad = Module._load;
Module._load = function load(request, parent, isMain) {
  if (/localization\/localeTools$/.test(request)) {
    return { tr: key => String(key) };
  }
  return originalLoad.call(this, request, parent, isMain);
};

const { buildThemeColors } = require('../../ts/themes/allThemes');

const vars = buildThemeColors('classic-light');
const lines = Object.entries(vars)
  // these are chosen by the popups skin itself (surface, accent), not taken from the theme
  .filter(([k]) => !['--primary-color'].includes(k))
  .map(([k, v]) => `  ${k}: ${v};`);

const out = `// GENERATED by web/tools/gen-light-popup-vars.js from ts/themes (Classic Light). Do not edit.
// Mixin with every colour variable of the app's light theme.
@mixin light-popup-vars {
${lines.join('\n')}
}
`;
fs.writeFileSync(path.join(__dirname, '../styles/light-popup-vars.scss'), out);
console.log(`wrote ${lines.length} variables`);
